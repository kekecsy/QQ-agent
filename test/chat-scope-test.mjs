import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'chat-scope-'));
process.env.QQ_AGENT_DATA_DIR = dir;
try {
  const { normalizeChatScope, extensionAllowsChat, withExtensionContext } = await import('../src/skills/chat-scope.js');
  const { updateConfig } = await import('../src/config.js');
  const { skillManager } = await import('../src/skills/manager.js');
  const { normalizeManifest } = await import('../src/skills/manifest.js');
  const { registerTool, getToolAvailability } = await import('../src/tool-registry.js');
  const { executeTool } = await import('../src/tools.js');
  const { SendQueue } = await import('../src/sender.js');
  const only = { mode: 'only', chats: ['group:1'] };
  assert.deepEqual(normalizeChatScope({ ...only, chats: ['group:1', 'group:1'] }), only);
  for (const invalid of [{}, { mode: 'only', chats: ['1'] }, { mode: 'unknown', chats: [] }, { mode: 'only', chats: ['group:0'] }]) assert.throws(() => normalizeChatScope(invalid));
  assert.equal(extensionAllowsChat({}, 'group:2'), true);
  assert.equal(extensionAllowsChat({ chatScope: only }, 'group:1'), true);
  assert.equal(extensionAllowsChat({ chatScope: only }, 'private:1'), false);
  assert.equal(extensionAllowsChat({ chatScope: { mode: 'only', chats: [] } }, 'group:1'), false);
  assert.equal(extensionAllowsChat({ chatScope: { mode: 'except', chats: ['group:1'] } }, 'group:2'), true);
  assert.equal(extensionAllowsChat({ chatScope: { mode: 'except', chats: ['group:1'] } }, 'group:1'), false);
  let hooks = 0;
  let tools = 0;
  const manifest = normalizeManifest({ id: 'scope-demo', name: 'Scoped', version: '1.0.0', apiVersion: 1,
    capabilities: ['scope.test'], prompt: { sections: [{ id: 'scope-test', content: 'only group one' }] } }).manifest;
  skillManager.register({ manifest, providers: { 'scope.test': () => 'ok' }, hooks: { test: () => { hooks++; } } });
  updateConfig({ skills: { 'scope-demo': { enabled: true, chatScope: only } }, send: { minGapMs: 0, maxGapMs: 0, byLengthMs: 0 } });
  assert.equal(skillManager.isActive('scope-demo', { chatKey: 'group:1' }).active, true);
  assert.equal(skillManager.isActive('scope-demo', { chatKey: 'group:2' }).code, 'chat-scope-disabled');
  assert.equal(skillManager.getCapabilityProviders('scope.test', { chatKey: 'group:2' }).length, 0);
  assert.equal(skillManager.getPromptSections({ chatKey: 'group:2' }).length, 0);
  assert.ok(skillManager.getPromptSections({ chatKey: 'group:1' }).length);
  await skillManager.runHook('test', { chatKey: 'group:2' });
  await skillManager.runHook('test', { chatKey: 'group:1' });
  assert.equal(hooks, 1);
  await withExtensionContext({ chatKey: 'group:2' }, async () => {
    await Promise.resolve();
    assert.equal(skillManager.getCapabilityProviders('scope.test').length, 0);
  });
  const def = { id: 'scope_demo', name: 'scope tool', skillId: 'scope-demo', execute: () => { tools++; return { content: 'ok' }; } };
  registerTool(def);
  assert.equal(getToolAvailability(def.id, { runtimeContext: { chatKey: 'group:2' } }).enabled, false);
  assert.equal((await executeTool([def], { chatKey: 'group:2' }, def.id, {})).isError, true);
  await executeTool([def], { chatKey: 'group:1' }, def.id, {});
  assert.equal(tools, 1);
  let transcriptions = 0;
  skillManager.register({ manifest: normalizeManifest({ id: 'scoped-stt', capabilities: ['media.transcribe'] }).manifest,
    providers: { 'media.transcribe': () => { transcriptions++; return { ok: true, text: 'decoded' }; } } });
  updateConfig({ skills: { 'scoped-stt': { chatScope: only } } });
  const { segmentsToText } = await import('../src/onebot.js');
  assert.equal(await segmentsToText([{ type: 'record', data: {} }], { chatKey: 'group:2', onebot: {} }), '[语音]');
  assert.equal(await segmentsToText([{ type: 'record', data: {} }], { chatKey: 'group:1', onebot: {} }), '[语音转文字] decoded');
  assert.equal(transcriptions, 1, 'incoming audio respects scope before transcription');
  const provider = skillManager.getCapabilityProviders('scope.test', { chatKey: 'group:1' })[0];
  updateConfig({ skills: { 'scope-demo': { chatScope: { mode: 'only', chats: [] } } } });
  assert.equal(provider.fn(), undefined, 'cached provider must recheck live scope');
  const sender = new SendQueue({ onebot: { sendText: () => { throw new Error('must not send'); } }, store: {} });
  await assert.rejects(withExtensionContext({ skillId: 'scope-demo' }, () => sender.sendTextBatch('group:2', ['blocked'])), /未启用该扩展/);
  updateConfig({ skills: { 'scope-demo': { enabled: false, chatScope: { mode: 'all', chats: [] } } } });
  assert.equal(skillManager.isActive('scope-demo', { chatKey: 'group:1' }).active, false, 'global off cannot be overridden');
  const { createRoutes } = await import('../src/routes.js');
  const routes = createRoutes({ readBody: async (req) => req.body, sanitizeConfig: () => ({}), emit: () => {} });
  const route = routes.find((r) => r.method === 'POST' && r.pattern instanceof RegExp && r.pattern.test('/api/skills/scope-demo'));
  let response;
  const json = (_res, status, value) => { response = { status, value }; };
  await route.handler({ req: { body: { chatScope: only } }, json, match: ['/api/skills/scope-demo', 'scope-demo'] });
  assert.equal(response.status, 200);
  assert.deepEqual(response.value.settings.chatScope, only);
  await route.handler({ req: { body: { enabled: true, chatScope: { mode: 'bad' } } }, json, match: ['', 'scope-demo'] });
  assert.equal(response.status, 400);
  assert.equal(skillManager.isEnabled('scope-demo'), false, 'invalid scope must not partially enable extension');
  const repeat = await import('../plugins/repeat-echo/index.js');
  const quick = await import('../plugins/ygo-quick-card/index.js');
  const fakeApi = { config: () => ({}), isEnabledForChat: () => false, log: () => {}, registerTool: () => {} };
  await repeat.setup(fakeApi);
  await quick.setup(fakeApi);
  const { Orchestrator } = await import('../src/orchestrator.js');
  let observed = 0;
  repeat.internals.engine.judge = () => { observed++; };
  repeat.internals.install();
  try {
    Orchestrator.prototype.onIncoming.call({ paused: true }, 'group:2', { text: 'repeat' });
    assert.equal(observed, 0, 'native repeat interceptor must not inspect excluded chats');
  } finally { repeat.dispose(); }
  let passed = 0;
  quick.internals.route({}, () => { passed++; }, 'group:2', { text: '查卡' });
  assert.equal(passed, 1, 'disabled quick card must pass through to ordinary chat');
  quick.dispose();
  const relay = await import('../plugins/forward-relay/index.js');
  await relay.setup(fakeApi);
  await assert.rejects(relay.internals.sendForward('group', '1', { srcGroup: '2' }), /来源群未启用/);
  relay.dispose();
  console.log('PASS: per-chat prompts/tools/hooks/capabilities, direct execution, live changes, outbound guard and legacy defaults');
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
