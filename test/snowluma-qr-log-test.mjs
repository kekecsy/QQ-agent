import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx = vm.createContext({ Date, esc: (s) => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;') });
vm.runInContext(fs.readFileSync(new URL('../ui/app/03-snowluma.js', import.meta.url), 'utf8'), ctx);
const row = '    ████▀▀████    ';
assert.equal(ctx.formatSnowlumaLogs([{ at: 0, text: `\x1b[32m${row}\x1b[0m` }]), row);
const sparse = ' ▄    ▀  ▄         ▀ ';
assert.equal(ctx.formatSnowlumaLogs([{ at: 0, text: sparse }]), sparse);
const normal = ctx.formatSnowlumaLogs([{ at: 0, text: '\x1b[33mhello\x1b[0m' }]);
assert.ok(normal.includes('hello') && !normal.includes('\x1b'));
assert.equal(ctx.formatSnowlumaLogs([]), '暂无日志');
const css = fs.readFileSync(new URL('../ui/style.css', import.meta.url), 'utf8');
assert.match(css, /#sl-logs-view\s*\{[^}]*white-space: pre;/);
assert.match(css, /\.sl-qr-block\s*\{[^}]*line-height: 1;/);
const html = ctx.renderSnowlumaLogHtml(`hello\n${row}\n${sparse}\n<script>`);
assert.equal((html.match(/class="sl-qr-block"/g) || []).length, 1);
assert.ok(html.includes('&lt;script&gt;'));
console.log('PASS: QR spacing, ANSI removal, timestamp handling and nonwrapping layout');
