import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'qq-faces-'));
process.env.QQ_AGENT_DATA_DIR = dir;
try {
  const { qqFaceName, describeQqFaces } = await import('../src/qq-faces.js');
  const { segmentsToText, extractMediaFromSegments, expandForwardNodes } = await import('../src/onebot.js');
  const { formatHistoryEntries, buildTriggerBlock } = await import('../src/prompt.js');
  const { buildToolDefs, executeTool } = await import('../src/tools.js');
  const { ChatStore } = await import('../src/store.js');
  assert.equal(qqFaceName(3), '/发呆');
  assert.equal(qqFaceName('30'), '/奋斗');
  assert.equal(qqFaceName('32'), '/疑问');
  assert.equal(qqFaceName('352'), '/咦');
  assert.equal(qqFaceName('999999'), '');
  assert.equal(qqFaceName('__proto__'), '');
  const segments = [{ type: 'text', data: { text: '嗯' } }, { type: 'face', data: { id: 3 } }, { type: 'face', data: { id: '30' } }];
  assert.equal(await segmentsToText(segments), '嗯[QQ表情:/发呆][QQ表情:/奋斗]');
  assert.equal(await segmentsToText([{ type: 'face', data: { id: '999999' } }]), '[表情999999]');
  assert.equal(await segmentsToText('[CQ:face,id=3]'), '[QQ表情:/发呆]');
  const media = extractMediaFromSegments(segments);
  assert.equal(media[1].faceId, '30');
  assert.equal(media[1].faceName, '/奋斗');
  const original = { id: 1, mid: 42, ts: Date.now(), senderId: 'someone', senderName: '群友', text: '[表情30]', media: [{ kind: 'face', faceId: '30' }] };
  assert.match(formatHistoryEntries([original]).join('\n'), /QQ表情:\/奋斗/);
  assert.match(buildTriggerBlock([original], {}), /QQ表情:\/奋斗/);
  assert.equal(original.text, '[表情30]', 'rendering does not rewrite the archive');
  assert.equal(describeQqFaces('[表情包:收藏图] /发呆 [表情999999]'), '[表情包:收藏图] /发呆 [表情999999]');
  const forward = await expandForwardNodes([{ user_id: 1, nickname: '甲', content: segments }]);
  assert.match(forward.text, /QQ表情:\/发呆/);
  const store = new ChatStore();
  store.appendIncoming('group:1', original);
  const ctx = { chatKey: 'group:1', store, session: { pastStateCount: 0 } };
  const defs = buildToolDefs();
  const read = (r) => JSON.parse(r.content);
  const images = read(await executeTool(defs, ctx, 'get_message_images', { messageId: 42 }));
  assert.equal(images.faces[0].name, '/奋斗', 'image tool returns known face meaning without calling vision');
  const detail = read(await executeTool(defs, ctx, 'get_message_detail', { messageId: 42 }));
  assert.equal(detail.text, '[QQ表情:/奋斗]');
  const recent = read(await executeTool(defs, ctx, 'get_recent_messages', {}));
  assert.equal(recent.messages[0].text, '[QQ表情:/奋斗]');
  console.log('PASS: official names, protocol IDs, unknown fallback, old/new prompts, forwards and history tools');
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
