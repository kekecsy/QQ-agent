import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'recovery-plugin-'));
process.env.QQ_AGENT_DATA_DIR = path.join(dir, 'data');
try {
  const { ChatStore } = await import('../src/store.js');
  const { loadPlugins, unloadSkill } = await import('../src/plugin-loader.js');
  const { skillManager } = await import('../src/skills/manager.js');
  const { getTool, getToolAvailability } = await import('../src/tool-registry.js');
  const { updateConfig } = await import('../src/config.js');
  const { sendIdentity, recordSendFailure } = await import('../src/send-failures.js');
  const { Orchestrator } = await import('../src/orchestrator.js');
  fs.mkdirSync(path.join(dir, 'plugins'));
  fs.mkdirSync(path.join(dir, 'skills'));
  fs.cpSync(path.resolve('plugins/message-recovery'), path.join(dir, 'plugins/message-recovery'), { recursive: true });
  fs.symlinkSync(path.resolve('src'), path.join(dir, 'src'));
  await loadPlugins({ roots: { plugins: path.join(dir, 'plugins'), skills: path.join(dir, 'skills') }, log: () => {} });
  const id = 'message-recovery__get_recovery_messages';
  const tool = getTool(id);
  assert.ok(tool);
  assert.equal(getTool('get_recovery_messages'), null);
  assert.equal(Orchestrator.prototype.startRecoveryLoop, undefined);
  assert.equal(Orchestrator.prototype.checkRecovery, undefined);
  const store = new ChatStore();
  const add = (mid, hours) => store.appendIncoming('group:1', { mid, ts: Date.now() - hours * 3600000, senderId: 'a', text: '[图片]', media: [{ kind: 'image' }] });
  add(1, 13); add(2, 1); add(3, 1);
  store.markRecalled('group:1', 3);
  recordSendFailure(sendIdentity('send_group_msg', { group_id: 1, message: [{ type: 'reply', data: { id: 2 } }, { type: 'text', data: { text: '失败原文' } }] }), 'retcode=200');
  recordSendFailure(sendIdentity('send_group_msg', { group_id: 2, message: [{ type: 'text', data: { text: '其他群私密信息' } }] }), 'retcode=200');
  const result = JSON.parse((await tool.execute({ store, chatKey: 'group:1' }, {})).content);
  assert.deepEqual(result.messages.map((m) => m.messageId), [2]);
  assert.equal(result.failedSends.length, 1);
  assert.ok(!JSON.stringify(result).includes('其他群私密信息'));
  assert.ok(skillManager.getPromptSections({}).some((s) => s.content.includes(id)));
  updateConfig({ skills: { 'message-recovery': { enabled: false } } });
  assert.equal(getToolAvailability(id).enabled, false);
  assert.ok(!skillManager.getPromptSections({}).some((s) => s.content.includes(id)));
  unloadSkill('message-recovery');
  assert.equal(getTool(id), null);
  assert.ok(fs.existsSync(path.join(dir, 'data/send-failures.json')));
  console.log('PASS: plugin loading, enable/disable/unload, no timers, 12h and recalled/cross-chat filtering');
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
