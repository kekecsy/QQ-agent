/**
 * 红蓝配色的实现方式。
 *
 * 为什么不用 ANSI 颜色码：QQ 群消息是**纯文本**，ANSI 转义序列不会渲染，
 * 只会变成一堆不可见的怪字符。所以红蓝必须用**方块字符本身的语义色**：
 *   · 红 → 🟥（宿傩，恒定红 —— 他是诅咒之王，血条永远是红的）
 *   · 蓝 → 🟦（我方咒术师，恒定蓝）
 *
 * 这比 ◈◆ 这种纯形状方案更直观：一眼就分得清谁是谁。
 * 半格用 🟥/🟦 的"空"对应 —— emoji 没有半格，
 * 所以改成 10 格整块 + 百分比数字，牺牲一点精度换取清晰的配色。
 */
export const HP_BAR = {
  /** 用 emoji 方块做红蓝 */
  boss: '🟥',
  player: '🟦',
  /** 空的用暗色方块，视觉上像"血槽底" */
  empty: '⬛',
  cells: 10,
}

/**
 * 台词/旁白轮换：按回合数取，保证相邻回合不重复。
 *
 * ⚠️ 原来这个函数只在 index.js 里（私有）。真身台词与魔虚罗旁白也需要它，
 *    所以提到 visual.js 导出 —— 避免三处各抄一份，改一处漏两处。
 *
 * 用 `% length`（纯取模）而不是随机：随机会连着抽到同一句，
 * 而"按回合轮换"在最坏情况下也只是循环，不会重复相邻两条。
 */
export function pickLine(lines, turn) {
  if (!lines || !lines.length) return ''
  return lines[(Number(turn) || 0) % lines.length]
}

